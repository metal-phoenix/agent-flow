#!/usr/bin/env bash
# Generate the package inventory (SBOM) for the Agent Flow image.
#
#   scripts/sbom.sh [image]        # default: build via compose, then scan agent-flow:local
#
# Outputs (committed, read by Argus via the Prodigy copy below):
#   sbom/agent-flow.cdx.json   CycloneDX JSON (OS pkgs, npm, python if any)
#   sbom/agent-flow.md         readable table + base image, build date, git sha
# If SBOM_PUBLISH_DIR (default /home/scott/sbom/agent-flow) exists or can be
# created, the CycloneDX file is copied there too (skipped silently elsewhere).
#
# Env: SBOM_SKIP_BUILD=1 (scan existing image), SBOM_PUBLISH_DIR=<dir>,
#      SYFT_BIN=<path to an existing syft> (skips install, no checksum).
set -euo pipefail

SYFT_VERSION="1.18.1"
SYFT_SHA256_linux_amd64="066c251652221e4d44fcc4d115ce3df33a91769da38c830a8533199db2f65aab"
SYFT_SHA256_linux_arm64="cd228306e5cb0654baecb454f76611606b84899d27fa9ceb7da4df46b94fe84e"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/sbom"
IMAGE="${1:-agent-flow:local}"
PUBLISH_DIR="${SBOM_PUBLISH_DIR:-/home/scott/sbom/agent-flow}"
BIN_DIR="$ROOT/.bin"

die() { echo "sbom.sh: $*" >&2; exit 1; }
for c in docker jq sha256sum curl tar; do command -v "$c" >/dev/null || die "missing required tool: $c"; done

install_syft() {
  local os arch var want tmp
  os="$(uname -s | tr '[:upper:]' '[:lower:]')"
  case "$(uname -m)" in x86_64|amd64) arch=amd64;; aarch64|arm64) arch=arm64;; *) die "unsupported arch $(uname -m)";; esac
  var="SYFT_SHA256_${os}_${arch}"; want="${!var:-}"
  [ -n "$want" ] || die "no pinned checksum for ${os}_${arch}"
  tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
  curl -fsSL -o "$tmp/syft.tgz" "https://github.com/anchore/syft/releases/download/v${SYFT_VERSION}/syft_${SYFT_VERSION}_${os}_${arch}.tar.gz"
  echo "$want  $tmp/syft.tgz" | sha256sum -c - >/dev/null || die "syft checksum mismatch"
  tar -xzf "$tmp/syft.tgz" -C "$tmp" syft
  mkdir -p "$BIN_DIR"; install -m 0755 "$tmp/syft" "$BIN_DIR/syft-${SYFT_VERSION}"; rm -rf "$tmp"
}

if [ -n "${SYFT_BIN:-}" ]; then SYFT="$SYFT_BIN"
else
  SYFT="$BIN_DIR/syft-${SYFT_VERSION}"
  [ -x "$SYFT" ] || install_syft
fi

if [ "$#" -eq 0 ] && [ -z "${SBOM_SKIP_BUILD:-}" ]; then
  (cd "$ROOT" && docker compose build)
fi
docker image inspect "$IMAGE" >/dev/null 2>&1 || die "image '$IMAGE' not found (build it first)"

# Base image: last FROM in the Dockerfile (the runtime stage) + its digest.
BASE_REF="$(awk 'toupper($1)=="FROM"{i=2; while ($i ~ /^--/) i++; r=$i} END{print r}' "$ROOT/Dockerfile")"
BASE_DIGEST="$(docker image inspect "$BASE_REF" --format '{{index .RepoDigests 0}}' 2>/dev/null || true)"
[ -n "$BASE_DIGEST" ] || BASE_DIGEST="$(docker image inspect "$BASE_REF" --format '{{.Id}}' 2>/dev/null || echo unknown)"
BUILD_DATE="$(docker image inspect "$IMAGE" --format '{{.Created}}' 2>/dev/null || date -u +%FT%TZ)"
GIT_SHA="$(git -C "$ROOT" rev-parse HEAD 2>/dev/null || echo unknown)"
IMAGE_ID="$(docker image inspect "$IMAGE" --format '{{.Id}}')"

mkdir -p "$OUT"
RAW="$(mktemp)"; trap 'rm -f "$RAW"' EXIT
"$SYFT" scan "docker:${IMAGE}" -o cyclonedx-json="$RAW" -q

# Stamp provenance into the CycloneDX metadata (properties are free-form name/value).
# Drop the volatile serialNumber/timestamp so unchanged images give a stable diff.
jq --arg base "$BASE_REF" --arg digest "$BASE_DIGEST" --arg date "$BUILD_DATE" \
   --arg sha "$GIT_SHA" --arg img "$IMAGE" --arg id "$IMAGE_ID" '
  del(.serialNumber)
  | .metadata.timestamp = $date
  | .metadata.properties = ((.metadata.properties // []) + [
      {name:"agent-flow:image",value:$img},
      {name:"agent-flow:image-id",value:$id},
      {name:"agent-flow:base-image",value:$base},
      {name:"agent-flow:base-image-digest",value:$digest},
      {name:"agent-flow:build-date",value:$date},
      {name:"agent-flow:git-sha",value:$sha}])' "$RAW" > "$OUT/agent-flow.cdx.json"

# Type from purl (pkg:deb/..., pkg:npm/...) falling back to the component type.
{
  echo "# Agent Flow image package inventory"
  echo
  echo "- Image: \`$IMAGE\` ($IMAGE_ID)"
  echo "- Base image: \`$BASE_REF\` — \`$BASE_DIGEST\`"
  echo "- Build date: $BUILD_DATE"
  echo "- Git sha: \`$GIT_SHA\`"
  echo "- Generated by: \`scripts/sbom.sh\` (syft $SYFT_VERSION). Machine-readable: [agent-flow.cdx.json](agent-flow.cdx.json)"
  echo
  echo "| Name | Version | Type |"
  echo "|---|---|---|"
  jq -r '[.components[]? | select(.type != "file")
          | {n:.name, v:(.version // "-"), t:((.purl // "" | capture("^pkg:(?<t>[^/]+)/").t) // .type)}]
         | sort_by(.t, .n, .v)[] | "| \(.n) | \(.v) | \(.t) |"' "$OUT/agent-flow.cdx.json"
} > "$OUT/agent-flow.md"

echo "sbom.sh: wrote $OUT/agent-flow.cdx.json and agent-flow.md ($(jq '.components|length' "$OUT/agent-flow.cdx.json") components)"

if mkdir -p "$PUBLISH_DIR" 2>/dev/null && cp "$OUT/agent-flow.cdx.json" "$PUBLISH_DIR/agent-flow.cdx.json" 2>/dev/null; then
  echo "sbom.sh: copied CycloneDX to $PUBLISH_DIR/agent-flow.cdx.json"
else
  echo "sbom.sh: note: could not write $PUBLISH_DIR (not Prodigy?); skipped publish" >&2
fi
